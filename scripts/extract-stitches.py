#!/usr/bin/env python3
"""Extract the cross-stitch motifs from ucalyptus.me's background tile.

Reads stitch-tile-ink.svg (ucalyptus.github.io/assets/images/) and writes
stitches.js: the stitch geometry and each distinct motif shape as integer
stitch-grid offsets from its centre.

    python3 scripts/extract-stitches.py path/to/stitch-tile-ink.svg > stitches.js
"""

import math
import re
import sys
from collections import defaultdict

CLUSTER_GAP = 30  # tile units; stitches within one motif sit <= 16 apart, motifs >= 60


def main(svg_path):
    svg = open(svg_path, encoding="utf-8").read()
    size = float(re.search(r'viewBox="0 0 ([\d.]+) ', svg).group(1))
    stroke = float(re.search(r'stroke-width="([\d.]+)"', svg).group(1))
    segs = [tuple(map(float, m)) for m in re.findall(r"M([\d.]+) ([\d.]+)l(-?[\d.]+) (-?[\d.]+)", svg)]
    arm = abs(segs[0][2]) / 2

    # every stitch is two crossing diagonals that share a centre
    centres = sorted({(round(x + dx / 2, 2), round(y + dy / 2, 2)) for x, y, dx, dy in segs})

    def wrap(d):
        return d - size * round(d / size)

    parent = list(range(len(centres)))
    nearest = [math.inf] * len(centres)

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for i, a in enumerate(centres):
        for j in range(i + 1, len(centres)):
            b = centres[j]
            d = math.hypot(wrap(a[0] - b[0]), wrap(a[1] - b[1]))
            if d < CLUSTER_GAP:
                parent[find(i)] = find(j)
            if d > 1:  # the SVG repeats a few stitches exactly on top of each other
                nearest[i] = min(nearest[i], d)
                nearest[j] = min(nearest[j], d)

    # the stitch pitch is the smallest spacing between neighbouring stitches
    pitch = round(min(nearest), 1)

    clusters = defaultdict(list)
    for i, c in enumerate(centres):
        clusters[find(i)].append(c)

    shapes = []
    for pts in clusters.values():
        rx, ry = pts[0]
        pts = [(rx + wrap(x - rx), ry + wrap(y - ry)) for x, y in pts]  # unwrap across tile edges
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
        offsets = frozenset((round((x - cx) / pitch), round((y - cy) / pitch)) for x, y in pts)
        if offsets not in shapes:
            shapes.append(offsets)

    def flat(offsets):
        return ",".join(f"{x},{y}" for x, y in sorted(offsets, key=lambda p: (p[1], p[0])))

    out = [
        "// Generated by scripts/extract-stitches.py from ucalyptus.me's stitch-tile-ink.svg. Do not edit.",
        "window.STITCH_TILE = {",
        f"  size: {size:g}, pitch: {pitch:g}, arm: {arm:g}, stroke: {stroke:g},",
        "  // motif shapes: flat [x, y, ...] stitch offsets from the motif centre, in stitch-grid steps",
        "  shapes: [",
        *[f"    [{flat(s)}]," for s in shapes],
        "  ]",
        "};",
    ]
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
